# Detect potential outliers in selling prices
if "selling_price" in df.columns:
    # Remove missing selling prices
    prices = df["selling_price"].dropna()

    # Calculate the first and third quartiles
    Q1 = prices.quantile(0.25)
    Q3 = prices.quantile(0.75)

    # Calculate the interquartile range (IQR)
    IQR = Q3 - Q1

    # Calculate the lower and upper bounds
    lower_bound = Q1 - 1.5 * IQR
    upper_bound = Q3 + 1.5 * IQR

    # Identify potential price outliers
    outliers = df[
        (df["selling_price"] < lower_bound) |
        (df["selling_price"] > upper_bound)
    ]

    # Display the results
    print("Lower bound:", lower_bound)
    print("Upper bound:", upper_bound)
    print("Potential price outliers:", len(outliers))
    print(outliers.head())

